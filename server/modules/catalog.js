export const getTemplate = (id) => TEMPLATES.find((t) => t.id === id);

/** Valeur d'environnement d'un champ (booléens → true/false). */
export const fieldValue = (f, v) => (f.type === 'bool' ? bool(v === true || v === 'true') : String(v ?? ''));

/** Version publique (sans détails internes) pour le navigateur. */
export function publicCatalog() {
  return TEMPLATES.map((t) => ({
    id: t.id,
    name: t.name,
    category: t.category,
    icon: t.icon,
    gradient: t.gradient,
    description: t.description,
    image: t.image || null,
    ports: t.ports,
    volumes: t.volumes,
    fields: t.fields,
    memory: t.memory,
    console: t.console?.kind || null,
    fromRepo: !!t.fromRepo,
    custom: !!t.custom,
    notes: t.notes || null,
    hasSecrets: !!t.secretsFromLogs?.length,
  }));
}
